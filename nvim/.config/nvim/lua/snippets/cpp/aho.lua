local ls = require("luasnip")
local s = ls.snippet
local t = ls.text_node

ls.add_snippets("cpp", {

  s("aho", {
    t({
      "struct AhoCorasick {",
      "  vector<array<int, 26>> nxt;",
      "  vector<int> link, order;",
      "  vector<int> pat_node;",
      "  vector<long long> vis;",
      "  AhoCorasick() { new_node(); }",
      "  int new_node() {",
      "    array<int, 26> a;",
      "    a.fill(-1);",
      "    nxt.push_back(a);",
      "    link.push_back(0);",
      "    return (int)nxt.size() - 1;",
      "  }",
      "  int add(const string &p) {",
      "    int u = 0;",
      "    for (char ch : p) {",
      "      int c = ch - 'a';",
      "      if (nxt[u][c] == -1) nxt[u][c] = new_node();",
      "      u = nxt[u][c];",
      "    }",
      "    pat_node.push_back(u);",
      "    return (int)pat_node.size() - 1;",
      "  }",
      "  void build() {",
      "    queue<int> q;",
      "    for (int c = 0; c < 26; c++) {",
      "      int v = nxt[0][c];",
      "      if (v == -1) nxt[0][c] = 0;",
      "      else {",
      "        link[v] = 0;",
      "        q.push(v);",
      "      }",
      "    }",
      "    while (!q.empty()) {",
      "      int u = q.front();",
      "      q.pop();",
      "      order.push_back(u);",
      "      for (int c = 0; c < 26; c++) {",
      "        int v = nxt[u][c];",
      "        if (v == -1) nxt[u][c] = nxt[link[u]][c];",
      "        else {",
      "          link[v] = nxt[link[u]][c];",
      "          q.push(v);",
      "        }",
      "      }",
      "    }",
      "  }",
      "  vector<long long> count(const string &text) {",
      "    vis.assign(nxt.size(), 0);",
      "    int u = 0;",
      "    for (char ch : text) {",
      "      u = nxt[u][ch - 'a'];",
      "      vis[u]++;",
      "    }",
      "    for (int i = (int)order.size() - 1; i >= 0; i--) {",
      "      int v = order[i];",
      "      vis[link[v]] += vis[v];",
      "    }",
      "    vector<long long> res(pat_node.size(), 0);",
      "    for (int i = 0; i < (int)pat_node.size(); i++) res[i] = vis[pat_node[i]];",
      "    return res;",
      "  }",
      "};",
    }),
  }),
})
