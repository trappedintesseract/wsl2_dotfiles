local ls = require("luasnip")
local s = ls.snippet
local t = ls.text_node

ls.add_snippets("cpp", {

  s("lazyseg", {
    t({
      "template <typename T>",
      "struct LazySeg {",
      "  int n;",
      "  vector<T> sum, lazy;",
      "  LazySeg(const vector<T> &a) : n((int)a.size()), sum(4 * n, 0), lazy(4 * n, 0) {",
      "    build(1, 0, n - 1, a);",
      "  }",
      "  void build(int node, int l, int r, const vector<T> &a) {",
      "    if (l == r) { sum[node] = a[l]; return; }",
      "    int mid = (l + r) / 2;",
      "    build(2 * node, l, mid, a);",
      "    build(2 * node + 1, mid + 1, r, a);",
      "    sum[node] = sum[2 * node] + sum[2 * node + 1];",
      "  }",
      "  void apply(int node, int l, int r, T v) {",
      "    sum[node] += v * (T)(r - l + 1);",
      "    lazy[node] += v;",
      "  }",
      "  void push(int node, int l, int r) {",
      "    if (lazy[node] == 0 || l == r) return;",
      "    int mid = (l + r) / 2;",
      "    apply(2 * node, l, mid, lazy[node]);",
      "    apply(2 * node + 1, mid + 1, r, lazy[node]);",
      "    lazy[node] = 0;",
      "  }",
      "  void add(int node, int l, int r, int ql, int qr, T v) {",
      "    if (qr < l || r < ql) return;",
      "    if (ql <= l && r <= qr) { apply(node, l, r, v); return; }",
      "    push(node, l, r);",
      "    int mid = (l + r) / 2;",
      "    add(2 * node, l, mid, ql, qr, v);",
      "    add(2 * node + 1, mid + 1, r, ql, qr, v);",
      "    sum[node] = sum[2 * node] + sum[2 * node + 1];",
      "  }",
      "  T query(int node, int l, int r, int ql, int qr) {",
      "    if (qr < l || r < ql) return 0;",
      "    if (ql <= l && r <= qr) return sum[node];",
      "    push(node, l, r);",
      "    int mid = (l + r) / 2;",
      "    return query(2 * node, l, mid, ql, qr) + query(2 * node + 1, mid + 1, r, ql, qr);",
      "  }",
      "  void range_add(int l, int r, T v) { add(1, 0, n - 1, l, r, v); }",
      "  T range_sum(int l, int r) { return query(1, 0, n - 1, l, r); }",
      "};",
    }),
  }),
})
