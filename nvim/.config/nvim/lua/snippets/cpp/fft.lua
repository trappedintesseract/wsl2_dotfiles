local ls = require("luasnip")
local s = ls.snippet
local t = ls.text_node

ls.add_snippets("cpp", {

  s("fft", {
    t({
      "void fft(vector<complex<double>> &a, bool invert) {",
      "  int n = (int)a.size();",
      "  for (int i = 1, j = 0; i < n; i++) {",
      "    int bit = n >> 1;",
      "    for (; j & bit; bit >>= 1) j ^= bit;",
      "    j ^= bit;",
      "    if (i < j) swap(a[i], a[j]);",
      "  }",
      "  for (int len = 2; len <= n; len <<= 1) {",
      "    double ang = 2 * acos(-1.0) / len * (invert ? -1 : 1);",
      "    complex<double> wlen(cos(ang), sin(ang));",
      "    for (int i = 0; i < n; i += len) {",
      "      complex<double> w(1);",
      "      for (int j = 0; j < len / 2; j++) {",
      "        complex<double> u = a[i + j], v = a[i + j + len / 2] * w;",
      "        a[i + j] = u + v;",
      "        a[i + j + len / 2] = u - v;",
      "        w *= wlen;",
      "      }",
      "    }",
      "  }",
      "  if (invert)",
      "    for (auto &x : a) x /= n;",
      "}",
      "",
      "vector<long long> convolution(const vector<long long> &a, const vector<long long> &b) {",
      "  if (a.empty() || b.empty()) return {};",
      "  vector<complex<double>> fa(a.begin(), a.end()), fb(b.begin(), b.end());",
      "  int n = 1;",
      "  while (n < (int)(a.size() + b.size())) n <<= 1;",
      "  fa.resize(n);",
      "  fb.resize(n);",
      "  fft(fa, false);",
      "  fft(fb, false);",
      "  for (int i = 0; i < n; i++) fa[i] *= fb[i];",
      "  fft(fa, true);",
      "  vector<long long> res(a.size() + b.size() - 1);",
      "  for (int i = 0; i < (int)res.size(); i++) res[i] = llround(fa[i].real());",
      "  return res;",
      "}",
    }),
  }),
})
