local ls = require("luasnip")
local s = ls.snippet
local t = ls.text_node

ls.add_snippets("cpp", {

  s("hld", {
    t({
      "struct HLD {",
      "  int n;",
      "  vector<int> parent, depth, sz, heavy, head, pos;",
      "  vector<long long> bit;",
      "  HLD(int n, const vector<vector<int>> &adj, const vector<long long> &val, int root) : n(n) {",
      "    parent.assign(n + 1, 0);",
      "    depth.assign(n + 1, 0);",
      "    sz.assign(n + 1, 0);",
      "    heavy.assign(n + 1, 0);",
      "    head.assign(n + 1, 0);",
      "    pos.assign(n + 1, 0);",
      "    bit.assign(n + 1, 0);",
      "    auto go1 = [&](auto &&self, int u, int p) -> void {",
      "      parent[u] = p;",
      "      depth[u] = depth[p] + 1;",
      "      sz[u] = 1;",
      "      for (int v : adj[u])",
      "        if (v != p) {",
      "          self(self, v, u);",
      "          sz[u] += sz[v];",
      "          if (heavy[u] == 0 || sz[v] > sz[heavy[u]]) heavy[u] = v;",
      "        }",
      "    };",
      "    go1(go1, root, 0);",
      "    int cur = 0;",
      "    auto go2 = [&](auto &&self, int u, int h) -> void {",
      "      head[u] = h;",
      "      pos[u] = cur++;",
      "      if (heavy[u]) self(self, heavy[u], h);",
      "      for (int v : adj[u])",
      "        if (v != parent[u] && v != heavy[u]) self(self, v, v);",
      "    };",
      "    go2(go2, root, root);",
      "    for (int u = 1; u <= n; u++) add(u, val[u]);",
      "  }",
      "  void add(int u, long long delta) {",
      "    for (int i = pos[u] + 1; i <= n; i += i & -i) bit[i] += delta;",
      "  }",
      "  long long pref(int i) const {",
      "    long long s = 0;",
      "    for (; i > 0; i -= i & -i) s += bit[i];",
      "    return s;",
      "  }",
      "  long long path_sum(int u, int v) const {",
      "    long long res = 0;",
      "    while (head[u] != head[v]) {",
      "      if (depth[head[u]] < depth[head[v]]) swap(u, v);",
      "      res += pref(pos[u] + 1) - pref(pos[head[u]]);",
      "      u = parent[head[u]];",
      "    }",
      "    if (depth[u] > depth[v]) swap(u, v);",
      "    return res + pref(pos[v] + 1) - pref(pos[u]);",
      "  }",
      "};",
    }),
  }),
})
