local ls = require("luasnip")
local s = ls.snippet
local t = ls.text_node

ls.add_snippets("cpp", {

  s("mcmf", {
    t({
      "struct MCMF {",
      "  struct Edge { int to, rev; long long cap, cost; };",
      "  int n;",
      "  vector<vector<Edge>> g;",
      "  MCMF(int n) : n(n), g(n + 1) {}",
      "  void add(int u, int v, long long cap, long long cost) {",
      "    g[u].push_back({v, (int)g[v].size(), cap, cost});",
      "    g[v].push_back({u, (int)g[u].size() - 1, 0, -cost});",
      "  }",
      "  pair<long long, long long> run(int src, int snk) {",
      "    long long flow = 0, cost = 0;",
      "    while (true) {",
      "      vector<long long> dist(n + 1, LLONG_MAX);",
      "      vector<int> pv(n + 1, -1), pe(n + 1, -1), inq(n + 1, 0);",
      "      deque<int> q;",
      "      dist[src] = 0;",
      "      q.push_back(src);",
      "      inq[src] = 1;",
      "      while (!q.empty()) {",
      "        int u = q.front();",
      "        q.pop_front();",
      "        inq[u] = 0;",
      "        for (int i = 0; i < (int)g[u].size(); i++) {",
      "          auto &e = g[u][i];",
      "          if (e.cap > 0 && dist[u] + e.cost < dist[e.to]) {",
      "            dist[e.to] = dist[u] + e.cost;",
      "            pv[e.to] = u;",
      "            pe[e.to] = i;",
      "            if (!inq[e.to]) { inq[e.to] = 1; q.push_back(e.to); }",
      "          }",
      "        }",
      "      }",
      "      if (dist[snk] == LLONG_MAX) break;",
      "      long long push = LLONG_MAX;",
      "      for (int v = snk; v != src; v = pv[v]) push = min(push, g[pv[v]][pe[v]].cap);",
      "      for (int v = snk; v != src; v = pv[v]) {",
      "        auto &e = g[pv[v]][pe[v]];",
      "        e.cap -= push;",
      "        g[v][e.rev].cap += push;",
      "      }",
      "      flow += push;",
      "      cost += push * dist[snk];",
      "    }",
      "    return pair{flow, cost};",
      "  }",
      "};",
    }),
  }),
})
