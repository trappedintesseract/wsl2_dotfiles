local ls = require("luasnip")
local s = ls.snippet
local t = ls.text_node

ls.add_snippets("cpp", {

  s("spf", {
    t({
      "struct NumberTheory {",
      "  vector<int> spf, phi, mu, primes;",
      "  NumberTheory(int n) {",
      "    spf.assign(n + 1, 0);",
      "    phi.assign(n + 1, 0);",
      "    mu.assign(n + 1, 0);",
      "    if (n >= 1) {",
      "      phi[1] = 1;",
      "      mu[1] = 1;",
      "    }",
      "    for (int i = 2; i <= n; i++) {",
      "      if (spf[i] == 0) {",
      "        spf[i] = i;",
      "        primes.push_back(i);",
      "        phi[i] = i - 1;",
      "        mu[i] = -1;",
      "      }",
      "      for (int p : primes) {",
      "        if (p > spf[i] || 1LL * i * p > n) break;",
      "        spf[i * p] = p;",
      "        if (i % p == 0) {",
      "          phi[i * p] = phi[i] * p;",
      "          mu[i * p] = 0;",
      "        } else {",
      "          phi[i * p] = phi[i] * (p - 1);",
      "          mu[i * p] = -mu[i];",
      "        }",
      "      }",
      "    }",
      "  }",
      "  vector<pair<int, int>> factorize(int x) const {",
      "    vector<pair<int, int>> res;",
      "    while (x > 1) {",
      "      int p = spf[x], c = 0;",
      "      while (x % p == 0) {",
      "        x /= p;",
      "        c++;",
      "      }",
      "      res.push_back({p, c});",
      "    }",
      "    return res;",
      "  }",
      "};",
    }),
  }),
})
