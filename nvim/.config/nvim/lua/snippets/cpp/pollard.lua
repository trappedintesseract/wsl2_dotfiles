local ls = require("luasnip")
local s = ls.snippet
local t = ls.text_node

ls.add_snippets("cpp", {

  s("pollard", {
    t({
      "struct Pollard {",
      "  static long long mul_mod(long long a, long long b, long long m) { return (long long)((__int128)a * b % m); }",
      "  static long long power(long long a, long long e, long long m) {",
      "    long long r = 1 % m;",
      "    a %= m;",
      "    while (e > 0) {",
      "      if (e & 1) r = mul_mod(r, a, m);",
      "      a = mul_mod(a, a, m);",
      "      e >>= 1;",
      "    }",
      "    return r;",
      "  }",
      "  static bool is_prime(long long n) {",
      "    if (n < 2) return false;",
      "    for (long long p : {2LL, 3LL, 5LL, 7LL, 11LL, 13LL, 17LL, 19LL, 23LL, 29LL, 31LL, 37LL})",
      "      if (n % p == 0) return n == p;",
      "    long long d = n - 1, s = 0;",
      "    while (d % 2 == 0) { d /= 2; s++; }",
      "    for (long long a : {2LL, 3LL, 5LL, 7LL, 11LL, 13LL, 17LL, 19LL, 23LL, 29LL, 31LL, 37LL}) {",
      "      long long x = power(a, d, n);",
      "      if (x == 1 || x == n - 1) continue;",
      "      bool composite = true;",
      "      for (long long i = 1; i < s; i++) {",
      "        x = mul_mod(x, x, n);",
      "        if (x == n - 1) { composite = false; break; }",
      "      }",
      "      if (composite) return false;",
      "    }",
      "    return true;",
      "  }",
      "  static long long rho(long long n) {",
      "    if (n % 2 == 0) return 2;",
      "    for (long long c = 1;; c++) {",
      "      long long x = 2, y = 2, d = 1;",
      "      auto f = [&](long long v) { return (mul_mod(v, v, n) + c) % n; };",
      "      while (d == 1) {",
      "        x = f(x);",
      "        y = f(f(y));",
      "        d = std::gcd(std::llabs(x - y), n);",
      "      }",
      "      if (d != n) return d;",
      "    }",
      "  }",
      "  static void rec(long long n, vector<long long> &out) {",
      "    if (n == 1) return;",
      "    if (is_prime(n)) { out.push_back(n); return; }",
      "    long long d = rho(n);",
      "    rec(d, out);",
      "    rec(n / d, out);",
      "  }",
      "  static vector<long long> factorize(long long n) {",
      "    vector<long long> out;",
      "    rec(n, out);",
      "    sort(out.begin(), out.end());",
      "    return out;",
      "  }",
      "};",
    }),
  }),
})
