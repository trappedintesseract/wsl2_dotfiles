local ls = require("luasnip")
local s = ls.snippet
local t = ls.text_node

ls.add_snippets("cpp", {

  s("suffixauto", {
    t({
      "struct SuffixAutomaton {",
      "  struct State {",
      "    int len, link;",
      "    array<int, 26> next;",
      "  };",
      "  vector<State> st;",
      "  int last;",
      "  SuffixAutomaton() {",
      "    State s;",
      "    s.len = 0;",
      "    s.link = -1;",
      "    s.next.fill(-1);",
      "    st.push_back(s);",
      "    last = 0;",
      "  }",
      "  void extend(int c) {",
      "    State cur;",
      "    cur.len = st[last].len + 1;",
      "    cur.link = 0;",
      "    cur.next.fill(-1);",
      "    st.push_back(cur);",
      "    int v = (int)st.size() - 1, p = last;",
      "    while (p != -1 && st[p].next[c] == -1) {",
      "      st[p].next[c] = v;",
      "      p = st[p].link;",
      "    }",
      "    if (p == -1) st[v].link = 0;",
      "    else {",
      "      int q = st[p].next[c];",
      "      if (st[p].len + 1 == st[q].len) st[v].link = q;",
      "      else {",
      "        State clone = st[q];",
      "        clone.len = st[p].len + 1;",
      "        st.push_back(clone);",
      "        int cl = (int)st.size() - 1;",
      "        while (p != -1 && st[p].next[c] == q) {",
      "          st[p].next[c] = cl;",
      "          p = st[p].link;",
      "        }",
      "        st[q].link = st[v].link = cl;",
      "      }",
      "    }",
      "    last = v;",
      "  }",
      "  void build(const string &s) { for (char ch : s) extend(ch - 'a'); }",
      "  bool contains(const string &t) const {",
      "    int u = 0;",
      "    for (char ch : t) {",
      "      int c = ch - 'a';",
      "      if (st[u].next[c] == -1) return false;",
      "      u = st[u].next[c];",
      "    }",
      "    return true;",
      "  }",
      "  long long distinct_substrings() const {",
      "    long long res = 0;",
      "    for (int i = 1; i < (int)st.size(); i++) res += st[i].len - st[st[i].link].len;",
      "    return res;",
      "  }",
      "};",
    }),
  }),
})
