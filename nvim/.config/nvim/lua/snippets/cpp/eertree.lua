local ls = require("luasnip")
local s = ls.snippet
local t = ls.text_node

ls.add_snippets("cpp", {

  s("eertree", {
    t({
      "struct PalindromicTree {",
      "  struct Node {",
      "    array<int, 26> next;",
      "    int len, link, cnt;",
      "  };",
      "  vector<Node> t;",
      "  string s;",
      "  int last;",
      "  PalindromicTree() {",
      "    Node a, b;",
      "    a.next.fill(0);",
      "    a.len = -1;",
      "    a.link = 0;",
      "    a.cnt = 0;",
      "    b.next.fill(0);",
      "    b.len = 0;",
      "    b.link = 0;",
      "    b.cnt = 0;",
      "    t.push_back(a);",
      "    t.push_back(b);",
      "    last = 1;",
      "  }",
      "  int get_link(int v, int pos) const {",
      "    while (pos - 1 - t[v].len < 0 || s[pos - 1 - t[v].len] != s[pos]) v = t[v].link;",
      "    return v;",
      "  }",
      "  void add(char ch) {",
      "    s.push_back(ch);",
      "    int pos = (int)s.size() - 1, c = ch - 'a';",
      "    int cur = get_link(last, pos);",
      "    if (t[cur].next[c] == 0) {",
      "      Node nd;",
      "      nd.next.fill(0);",
      "      nd.len = t[cur].len + 2;",
      "      nd.cnt = 0;",
      "      nd.link = (nd.len == 1) ? 1 : t[get_link(t[cur].link, pos)].next[c];",
      "      t.push_back(nd);",
      "      t[cur].next[c] = (int)t.size() - 1;",
      "    }",
      "    last = t[cur].next[c];",
      "    t[last].cnt++;",
      "  }",
      "  long long distinct() const { return (long long)t.size() - 2; }",
      "  vector<long long> occurrences() const {",
      "    vector<long long> c(t.size());",
      "    for (int i = 0; i < (int)t.size(); i++) c[i] = t[i].cnt;",
      "    vector<int> ord(t.size());",
      "    iota(ord.begin(), ord.end(), 0);",
      "    sort(ord.begin(), ord.end(), [&](int a, int b) { return t[a].len > t[b].len; });",
      "    for (int v : ord)",
      "      if (v > 1) c[t[v].link] += c[v];",
      "    return c;",
      "  }",
      "};",
    }),
  }),
})
