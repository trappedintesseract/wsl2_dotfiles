ls.add_snippets("cpp", {

  s("ntt", {
    t({
      "const long long NTT_MOD = 998244353;",
      "const long long NTT_ROOT = 3;",
      "",
      "long long ntt_power(long long a, long long e, long long mod) {",
      "  long long r = 1 % mod;",
      "  a %= mod;",
      "  while (e > 0) {",
      "    if (e & 1) r = r * a % mod;",
      "    a = a * a % mod;",
      "    e >>= 1;",
      "  }",
      "  return r;",
      "}",
      "",
      "void ntt(vector<long long> &a, bool invert) {",
      "  int n = (int)a.size();",
      "  for (int i = 1, j = 0; i < n; i++) {",
      "    int bit = n >> 1;",
      "    for (; j & bit; bit >>= 1) j ^= bit;",
      "    j ^= bit;",
      "    if (i < j) swap(a[i], a[j]);",
      "  }",
      "  for (int len = 2; len <= n; len <<= 1) {",
      "    long long wlen = ntt_power(NTT_ROOT, (NTT_MOD - 1) / len, NTT_MOD);",
      "    if (invert) wlen = ntt_power(wlen, NTT_MOD - 2, NTT_MOD);",
      "    for (int i = 0; i < n; i += len) {",
      "      long long w = 1;",
      "      for (int j = 0; j < len / 2; j++) {",
      "        long long u = a[i + j];",
      "        long long v = a[i + j + len / 2] * w % NTT_MOD;",
      "        a[i + j] = (u + v) % NTT_MOD;",
      "        a[i + j + len / 2] = (u - v + NTT_MOD) % NTT_MOD;",
      "        w = w * wlen % NTT_MOD;",
      "      }",
      "    }",
      "  }",
      "  if (invert) {",
      "    long long inv_n = ntt_power(n, NTT_MOD - 2, NTT_MOD);",
      "    for (auto &x : a) x = x * inv_n % NTT_MOD;",
      "  }",
      "}",
      "",
      "vector<long long> convolution_mod(const vector<long long> &a, const vector<long long> &b) {",
      "  if (a.empty() || b.empty()) return {};",
      "  vector<long long> fa(a.begin(), a.end()), fb(b.begin(), b.end());",
      "  int n = 1;",
      "  while (n < (int)(a.size() + b.size())) n <<= 1;",
      "  fa.resize(n);",
      "  fb.resize(n);",
      "  ntt(fa, false);",
      "  ntt(fb, false);",
      "  for (int i = 0; i < n; i++) fa[i] = fa[i] * fb[i] % NTT_MOD;",
      "  ntt(fa, true);",
      "  fa.resize(a.size() + b.size() - 1);",
      "  return fa;",
      "}",
    }),
  }),
})
