local ls = require("luasnip")
local s = ls.snippet
local t = ls.text_node

ls.add_snippets("cpp", {

  s("treap", {
    t({
      "struct ImplicitTreap {",
      "  struct Node {",
      "    int val, prio;",
      "    int sz;",
      "    Node *l, *r;",
      "    Node(int v) : val(v), prio(rand_prio()), sz(1), l(nullptr), r(nullptr) {}",
      "  };",
      "  static int rand_prio() {",
      "    static mt19937 g(987654321);",
      "    return (int)(g() & 0x7fffffff);",
      "  }",
      "  Node *root = nullptr;",
      "  static int size(Node *t) { return t ? t->sz : 0; }",
      "  static void upd(Node *t) { if (t) t->sz = 1 + size(t->l) + size(t->r); }",
      "  static void split(Node *t, int k, Node *&a, Node *&b) {",
      "    if (!t) { a = b = nullptr; return; }",
      "    if (size(t->l) >= k) { split(t->l, k, a, t->l); b = t; upd(b); }",
      "    else { split(t->r, k - size(t->l) - 1, t->r, b); a = t; upd(a); }",
      "  }",
      "  static Node *merge(Node *a, Node *b) {",
      "    if (!a) return b;",
      "    if (!b) return a;",
      "    if (a->prio > b->prio) { a->r = merge(a->r, b); upd(a); return a; }",
      "    b->l = merge(a, b->l); upd(b); return b;",
      "  }",
      "  void insert(int pos, int val) {",
      "    Node *a, *b;",
      "    split(root, pos, a, b);",
      "    root = merge(merge(a, new Node(val)), b);",
      "  }",
      "  void erase(int pos) {",
      "    Node *a, *b, *c;",
      "    split(root, pos, a, b);",
      "    split(b, 1, b, c);",
      "    root = merge(a, c);",
      "  }",
      "  int at(Node *t, int pos) const {",
      "    while (t) {",
      "      int lsz = size(t->l);",
      "      if (pos == lsz) return t->val;",
      "      if (pos < lsz) t = t->l;",
      "      else { pos -= lsz + 1; t = t->r; }",
      "    }",
      "    return -1;",
      "  }",
      "  int at(int pos) const { return at(root, pos); }",
      "  int size() const { return size(root); }",
      "  void to_vector(Node *t, vector<int> &out) const {",
      "    if (!t) return;",
      "    to_vector(t->l, out);",
      "    out.push_back(t->val);",
      "    to_vector(t->r, out);",
      "  }",
      "  vector<int> to_vector() const { vector<int> out; to_vector(root, out); return out; }",
      "};",
    }),
  }),
})
