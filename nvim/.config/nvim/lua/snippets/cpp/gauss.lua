local ls = require("luasnip")
local s = ls.snippet
local t = ls.text_node

ls.add_snippets("cpp", {

  s("gauss", {
    t({
      "long long modinv_local(long long a, long long mod) {",
      "  long long b = mod, u = 1, v = 0;",
      "  while (b) {",
      "    long long t = a / b;",
      "    a -= t * b;",
      "    swap(a, b);",
      "    u -= t * v;",
      "    swap(u, v);",
      "  }",
      "  return ((u % mod) + mod) % mod;",
      "}",
      "",
      "long long gauss_rank(vector<vector<long long>> a, long long mod) {",
      "  int n = (int)a.size(), m = n ? (int)a[0].size() : 0;",
      "  long long rank = 0;",
      "  for (int col = 0; col < m && rank < n; col++) {",
      "    int piv = -1;",
      "    for (int i = (int)rank; i < n; i++)",
      "      if (a[i][col] % mod) { piv = i; break; }",
      "    if (piv == -1) continue;",
      "    swap(a[piv], a[rank]);",
      "    long long iv = modinv_local(a[rank][col] % mod, mod);",
      "    for (int j = col; j < m; j++) a[rank][j] = a[rank][j] * iv % mod;",
      "    for (int i = 0; i < n; i++)",
      "      if (i != rank && a[i][col] % mod) {",
      "        long long f = a[i][col];",
      "        for (int j = col; j < m; j++) a[i][j] = ((a[i][j] - f * a[rank][j]) % mod + mod) % mod;",
      "      }",
      "    rank++;",
      "  }",
      "  return rank;",
      "}",
      "",
      "vector<long long> gauss_solve(vector<vector<long long>> a, vector<long long> b, long long mod) {",
      "  int n = (int)a.size(), m = n ? (int)a[0].size() : 0;",
      "  vector<int> where(m, -1);",
      "  int row = 0;",
      "  for (int col = 0; col < m && row < n; col++) {",
      "    int piv = -1;",
      "    for (int i = row; i < n; i++)",
      "      if (a[i][col] % mod) { piv = i; break; }",
      "    if (piv == -1) continue;",
      "    swap(a[piv], a[row]);",
      "    swap(b[piv], b[row]);",
      "    long long iv = modinv_local(a[row][col] % mod, mod);",
      "    for (int j = col; j < m; j++) a[row][j] = a[row][j] * iv % mod;",
      "    b[row] = b[row] * iv % mod;",
      "    for (int i = 0; i < n; i++)",
      "      if (i != row && a[i][col] % mod) {",
      "        long long f = a[i][col];",
      "        for (int j = col; j < m; j++) a[i][j] = ((a[i][j] - f * a[row][j]) % mod + mod) % mod;",
      "        b[i] = ((b[i] - f * b[row]) % mod + mod) % mod;",
      "      }",
      "    where[col] = row;",
      "    row++;",
      "  }",
      "  if (row < m) return {};",
      "  vector<long long> x(m, 0);",
      "  for (int col = 0; col < m; col++) x[col] = b[where[col]];",
      "  for (int i = 0; i < n; i++) {",
      "    long long s = 0;",
      "    for (int j = 0; j < m; j++) s = (s + a[i][j] * x[j]) % mod;",
      "    if (s != b[i] % mod) return {};",
      "  }",
      "  return x;",
      "}",
    }),
  }),
})
