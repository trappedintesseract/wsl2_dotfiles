local ls = require("luasnip")
local s = ls.snippet
local t = ls.text_node

ls.add_snippets("cpp", {

  s("dinic", {
    t({
      "struct Dinic {",
      "  struct Edge { int to, rev; long long cap; };",
      "  int n;",
      "  vector<vector<Edge>> g;",
      "  vector<int> level, iter;",
      "  Dinic(int n) : n(n), g(n + 1), level(n + 1), iter(n + 1) {}",
      "  void add(int u, int v, long long cap) {",
      "    g[u].push_back({v, (int)g[v].size(), cap});",
      "    g[v].push_back({u, (int)g[u].size() - 1, 0});",
      "  }",
      "  bool bfs(int src, int snk) {",
      "    fill(level.begin(), level.end(), -1);",
      "    queue<int> q;",
      "    level[src] = 0;",
      "    q.push(src);",
      "    while (!q.empty()) {",
      "      int u = q.front();",
      "      q.pop();",
      "      for (auto &e : g[u])",
      "        if (e.cap > 0 && level[e.to] < 0) { level[e.to] = level[u] + 1; q.push(e.to); }",
      "    }",
      "    return level[snk] >= 0;",
      "  }",
      "  long long dfs(int u, int snk, long long f) {",
      "    if (u == snk) return f;",
      "    for (int &i = iter[u]; i < (int)g[u].size(); i++) {",
      "      auto &e = g[u][i];",
      "      if (e.cap > 0 && level[e.to] == level[u] + 1) {",
      "        long long d = dfs(e.to, snk, min(f, e.cap));",
      "        if (d > 0) { e.cap -= d; g[e.to][e.rev].cap += d; return d; }",
      "      }",
      "    }",
      "    return 0;",
      "  }",
      "  long long maxflow(int src, int snk) {",
      "    long long flow = 0;",
      "    while (bfs(src, snk)) {",
      "      fill(iter.begin(), iter.end(), 0);",
      "      while (long long f = dfs(src, snk, LLONG_MAX)) flow += f;",
      "    }",
      "    return flow;",
      "  }",
      "};",
    }),
  }),
})
